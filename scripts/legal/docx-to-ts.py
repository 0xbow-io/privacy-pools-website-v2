"""Regenerate config/legal/{terms-of-use,privacy-policy}.ts from legal's .docx files.

  uv run --with python-docx python scripts/legal/docx-to-ts.py TERMS.docx PRIVACY.docx

The wording is copied verbatim. Only layout is normalised: tabs and runs of
spaces collapse to one space, empty paragraphs and zero-width characters are
dropped, auto-numbered paragraphs and hand-typed "o " sub-bullets become list
items, and short numbered or all-bold paragraphs become headings.
"""
import json, re, sys
from pathlib import Path
import docx
from docx.oxml.ns import qn

OUT = Path(__file__).resolve().parents[2] / 'config' / 'legal'
ZERO_WIDTH = re.compile('[​‌‍⁠﻿]')


def runs_of(p):
    out = []
    for r in p._p.iter(qn('w:r')):
        rpr = r.find(qn('w:rPr'))
        def on(tag):
            e = None if rpr is None else rpr.find(qn(tag))
            return e is not None and e.get(qn('w:val')) not in ('0', 'false', 'off', 'none')
        t = ''
        for c in r:
            if c.tag == qn('w:t'): t += c.text or ''
            elif c.tag == qn('w:tab'): t += '\t'
            elif c.tag in (qn('w:br'), qn('w:cr')): t += '\n'
            elif c.tag == qn('w:noBreakHyphen'): t += '-'
        if not t: continue
        st = (on('w:b'), on('w:i'), on('w:u'))
        if out and out[-1][1] == st: out[-1][0] += t
        else: out.append([t, st])
    return out


def numbering_format(d, num_id):
    root = d.part.numbering_part.element
    num = next(x for x in root.findall(qn('w:num')) if x.get(qn('w:numId')) == str(num_id))
    aid = num.find(qn('w:abstractNumId')).get(qn('w:val'))
    ab = next(x for x in root.findall(qn('w:abstractNum')) if x.get(qn('w:abstractNumId')) == aid)
    fmt = ab.find(qn('w:lvl')).find(qn('w:numFmt')).get(qn('w:val'))
    if fmt not in ('bullet', 'lowerLetter'):
        # Only these occur in the current docs. Any other format (e.g. decimal
        # section numbers) needs its rendered marker carried over: stop loudly.
        sys.exit(f'unsupported list numbering format {fmt!r} (numId {num_id})')
    return fmt


def convert(path, title):
    d = docx.Document(path)
    body = d.element.body
    if list(body.iter(qn('w:tbl'))) or list(body.iter(qn('w:sdt'))):
        sys.exit(f'{path}: tables or content controls are not converted, extend the script')
    blocks, updated = [], None
    for p in d.paragraphs:
        segs = []
        for t, (bo, it, un) in runs_of(p):
            t = re.sub(r'[ \t]+', ' ', ZERO_WIDTH.sub('', t.replace('\t', ' ')))
            s = {'t': t}
            if bo: s['b'] = 1
            if it: s['i'] = 1
            if un: s['u'] = 1
            segs.append(s)
        if not ''.join(s['t'] for s in segs).strip(): continue
        segs[0]['t'] = segs[0]['t'].lstrip(); segs[-1]['t'] = segs[-1]['t'].rstrip()
        segs = [s for s in segs if s['t']]
        plain = ''.join(s['t'] for s in segs)
        if plain.startswith('Last Updated:'):
            updated = plain[len('Last Updated:'):].strip(); continue
        if plain == title: continue
        b = {}
        pPr = p._p.pPr
        np_ = pPr.numPr if pPr is not None else None
        if np_ is None and p.style is not None and p.style.element.pPr is not None and p.style.element.pPr.numPr is not None:
            sys.exit(f'{path}: style-based numbering on {plain[:40]!r} is not converted')
        if np_ is not None:
            b['list'] = 'letter' if numbering_format(d, np_.numId.val) == 'lowerLetter' else 'bullet'
            b['level'] = np_.ilvl.val if np_.ilvl is not None else 0
        elif plain.startswith('o '):
            # A hand-typed Word sub-bullet glyph, not wording.
            segs[0]['t'] = segs[0]['t'][2:]
            b['list'], b['level'] = 'bullet', 1
        b['runs'] = segs
        if 'list' not in b and len(plain) < 90 and (re.match(r'^\d+\.\s', plain) or all(s.get('b') for s in segs)):
            b['heading'] = True
        blocks.append(b)
    return {'title': title, 'lastUpdated': updated, 'blocks': blocks}


def emit(doc, const, fname, source):
    body = json.dumps(doc, ensure_ascii=False, indent=2)
    (OUT / fname).write_text(
        f'// GENERATED by scripts/legal/docx-to-ts.py from "{source}".\n'
        '// The wording is verbatim. Layout only is normalised: whitespace collapsed,\n'
        '// empty paragraphs and zero-width characters dropped, hand-typed "o "\n'
        '// sub-bullets turned into list items. Do not edit by hand: rerun the\n'
        '// script on the final .docx from legal (the .docx is not committed).\n'
        "import type { LegalDocument } from './types';\n\n"
        f'export const {const}: LegalDocument = {body};\n')


terms_path, privacy_path = sys.argv[1], sys.argv[2]
emit(convert(terms_path, 'Terms of Use'), 'TERMS_OF_USE', 'terms-of-use.ts', Path(terms_path).name)
privacy = convert(privacy_path, 'Privacy Policy')
privacy['title'] = ''.join(r['t'] for r in privacy['blocks'].pop(0)['runs'])
emit(privacy, 'PRIVACY_POLICY', 'privacy-policy.ts', Path(privacy_path).name)
