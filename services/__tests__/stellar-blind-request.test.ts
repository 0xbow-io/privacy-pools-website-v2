// Blind Stellar payment requests end to end at the link level, against REAL
// vendored Stellar PoolSessions (memory storage, no network): the recipient's
// session generates the request, ppv2 wraps it in the v3 envelope and an
// xlm. link, and the payer side decodes it into exactly what the SDK's
// Stellar schema and prepareFulfillPaymentRequest accept. The link must never
// carry the recipient's G... address.
import { describe, expect, test } from 'bun:test';
import { Keypair } from '@stellar/stellar-sdk';

import {
  STELLAR_KEY_APP_IDENTIFIER,
  STELLAR_TESTNET_CONTRACTS,
  STELLAR_TESTNET_NETWORK,
} from '@/config/stellar-deployment';
import {
  parseStellarSdkPaymentRequestPayload,
  SHARED_NOTE_SECRET_PLACEHOLDER,
  stellarSdkPaymentRequestPayload,
  toStellarSdkPaymentRequest,
  type StellarSdkPaymentRequest,
} from '@/services/payment-request-codec';
import {
  createStellarRequest,
  decodeStellarPayLink,
  encodeStellarBlindRequest,
  encodeStellarRequest,
  isStellarRequestExpired,
  requestStates,
  STELLAR_REQUEST_PREFIX,
  stellarBlindRequestId,
} from '@/services/stellar/stellar-request';

const XLM = STELLAR_TESTNET_CONTRACTS.nativeAssetContractId;

class ReachedChain extends Error {}

// Every chain read throws this, so a test can tell "past validation, now at I/O" apart from a refusal.
const chainStub = new Proxy({}, {
  get: (_t, prop) => (prop === 'then' ? undefined : async () => { throw new ReachedChain('reached chain I/O'); }),
});

async function sessionFor(owner: string, seed = 'ab') {
  const sdk = await import('@privacy-pools-v2/stellar-sdk');
  const derived = new sdk.StellarCryptoService().deriveKeysFromSignature({
    signature: `0x${seed.repeat(64)}` as never,
    appIdentifier: STELLAR_KEY_APP_IDENTIFIER,
    revocableKeyIndex: '0x0' as never,
  });
  const session = await sdk.StellarPoolSessionBuilder.create({
    chainId: 202,
    ownerAddress: owner,
    rpcUrl: 'http://unused.invalid',
    rpcInteractor: chainStub,
    networkPassphrase: STELLAR_TESTNET_NETWORK.networkPassphrase,
    poolContractId: STELLAR_TESTNET_CONTRACTS.poolContractId,
    deploymentLedger: '1',
    ephemeralPaymentRequests: true,
    keystoreContractId: STELLAR_TESTNET_CONTRACTS.keystoreContractId,
    aspRegistryContractId: STELLAR_TESTNET_CONTRACTS.aspRegistryContractId,
    ipfsGatewayUrl: 'http://unused.invalid',
    protocolKeys: { ...derived, revocableKeyIndex: '0x0' },
    persistentStorage: { type: 'memory' },
    circuitArtifactsDir: '/nonexistent',
  } as never);
  return { sdk, session };
}

function linkJson(link: string): string {
  const b64 = link.slice(STELLAR_REQUEST_PREFIX.length).replace(/-/g, '+').replace(/_/g, '/');
  return Buffer.from(b64, 'base64').toString('utf8');
}

describe('blind Stellar payment request link', () => {
  test('generated by the SDK, wrapped as v3, decoded into what the Stellar schema accepts, naming no account', async () => {
    const owner = Keypair.random().publicKey();
    const { sdk, session } = await sessionFor(owner);
    const generated = await session.generatePaymentRequest({ amount: '0x989680', tokenId: XLM, slots: 5 }) as StellarSdkPaymentRequest;

    const envelope = stellarSdkPaymentRequestPayload(generated, 202);
    expect(envelope.kind).toBe('ppv2-sdk-payment-request');
    expect(envelope.chainId).toBe(202);
    expect('recipientAddress' in envelope).toBe(false);
    expect(envelope.noteSecretsMap.every(([, secret]) => secret === SHARED_NOTE_SECRET_PLACEHOLDER)).toBe(true);

    const link = encodeStellarBlindRequest(envelope);
    expect(link.startsWith(STELLAR_REQUEST_PREFIX)).toBe(true);
    const json = linkJson(link);
    expect(json).not.toContain(owner);
    expect(json).not.toContain(owner.toLowerCase());
    expect(json).not.toContain('recipient');
    expect(json).not.toContain('signature');

    const decoded = decodeStellarPayLink(link);
    expect(decoded.format).toBe('blind');
    if (decoded.format !== 'blind') return;
    // The C... StrKey is case-sensitive: kept exactly.
    expect(decoded.request.tokenId).toBe(XLM);

    const forSdk = toStellarSdkPaymentRequest(decoded.request);
    expect(forSdk).toEqual(generated);
    // The SDK's own Stellar parser accepts it (and the EVM one does not).
    expect(sdk.parsePaymentRequest(JSON.stringify(forSdk), sdk.StellarAddressSchema)).toEqual(generated as never);
    expect(() => sdk.parsePaymentRequest(JSON.stringify(forSdk))).toThrow();

    // The recipient's export carries the record, listed under the link's request id.
    const exported = await session.exportAccount();
    expect(requestStates(exported)).toEqual([{ paymentId: generated.paymentId, fulfilled: false, commitments: [] }]);
    expect(stellarBlindRequestId(generated.paymentId)).toMatch(/^[0-9a-f]{64}$/);
  });

  test("the payer's prepareFulfillPaymentRequest accepts the decoded request (and goes on to the chain)", async () => {
    const { session: recipient } = await sessionFor(Keypair.random().publicKey());
    const generated = await recipient.generatePaymentRequest({ amount: '0x989680', tokenId: XLM, slots: 5 }) as StellarSdkPaymentRequest;
    const decoded = decodeStellarPayLink(encodeStellarBlindRequest(stellarSdkPaymentRequestPayload(generated, 202)));
    if (decoded.format !== 'blind') throw new Error('expected blind');

    const { session: payer } = await sessionFor(Keypair.random().publicKey(), 'cd');
    const error = await payer.prepareFulfillPaymentRequest({
      paymentRequest: toStellarSdkPaymentRequest(decoded.request) as never,
      inputCommitments: [`0x${'11'.repeat(32)}`],
    }).then(() => null, (e: unknown) => e as Error);
    // Validation passed and the SDK went on to the chain (stubbed to throw), so the shape is right.
    expect(error).toBeInstanceOf(ReachedChain);

    // Control: the same request with an EVM tokenId is refused before any chain read.
    const refused = await payer.prepareFulfillPaymentRequest({
      paymentRequest: { ...toStellarSdkPaymentRequest(decoded.request), tokenId: `0x${'ee'.repeat(20)}` } as never,
      inputCommitments: [`0x${'11'.repeat(32)}`],
    }).then(() => null, (e: unknown) => e as Error);
    expect(refused).not.toBeNull();
    expect(refused).not.toBeInstanceOf(ReachedChain);
  });

  test('refuses a link that adds an address or a seal, another chain, another asset, or a mangled StrKey', async () => {
    const owner = Keypair.random().publicKey();
    const { session } = await sessionFor(owner);
    const generated = await session.generatePaymentRequest({ amount: '0x1', tokenId: XLM }) as StellarSdkPaymentRequest;
    const base = stellarSdkPaymentRequestPayload(generated, 202);
    const raw = (extra: Record<string, unknown>) => JSON.stringify({ ...base, ...extra });

    expect(() => parseStellarSdkPaymentRequestPayload(raw({ recipientAddress: owner }), 202)).toThrow();
    expect(() => parseStellarSdkPaymentRequestPayload(raw({ signature: { signer: '0x1' } }), 202)).toThrow();
    expect(() => parseStellarSdkPaymentRequestPayload(raw({}), 1)).toThrow();
    expect(() => parseStellarSdkPaymentRequestPayload(raw({ tokenId: XLM.toLowerCase() }), 202)).toThrow();
    const flipped = XLM.slice(0, -1) + (XLM.endsWith('A') ? 'B' : 'A');
    expect(() => parseStellarSdkPaymentRequestPayload(raw({ tokenId: flipped }), 202)).toThrow();
    expect(() => parseStellarSdkPaymentRequestPayload(raw({ tokenId: owner }), 202)).toThrow();
    expect(() => parseStellarSdkPaymentRequestPayload(raw({ amount: '0x0' }), 202)).toThrow();

    // A valid C... that is not this deployment's XLM is not payable here.
    const other = { ...base, tokenId: STELLAR_TESTNET_CONTRACTS.poolContractId };
    const otherLink = STELLAR_REQUEST_PREFIX + Buffer.from(JSON.stringify(other)).toString('base64url');
    expect(() => decodeStellarPayLink(otherLink)).toThrow('not valid for Stellar testnet');
  });

  test('carries the SDK deadline, so a lapsed request is refused before paying', async () => {
    const { session } = await sessionFor(Keypair.random().publicKey());
    const generated = await session.generatePaymentRequest({ amount: '0x1', tokenId: XLM }) as StellarSdkPaymentRequest;
    expect(generated.expiresAt).toBeDefined();
    const decoded = decodeStellarPayLink(encodeStellarBlindRequest(stellarSdkPaymentRequestPayload(generated, 202)));
    if (decoded.format !== 'blind') throw new Error('expected blind');
    expect(decoded.request.expiresAt).toBe(generated.expiresAt);
    expect(isStellarRequestExpired(decoded.request)).toBe(false);
    expect(isStellarRequestExpired(decoded.request, Number(BigInt(generated.expiresAt!)) + 1)).toBe(true);
  });
});

describe('old address-based Stellar links still open on the payer side', () => {
  test('decode as the address format with the recipient they name', () => {
    const recipient = Keypair.random().publicKey();
    const link = encodeStellarRequest(createStellarRequest({ recipient, amount: 10_000_000n, requestId: 'req-old-1' }));
    const decoded = decodeStellarPayLink(link);
    expect(decoded.format).toBe('address');
    if (decoded.format !== 'address') return;
    expect(decoded.request.recipient).toBe(recipient);
    expect(decoded.request.amount).toBe('10000000');
  });
});
